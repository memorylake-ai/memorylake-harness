#!/usr/bin/env node
// Generates the connector's "automatic memory" plugin from the MemoryLake
// plugin for WorkBuddy (../workbuddy-plugin), which stays the only place its
// hooks are written.
//
// A connector cannot carry hooks, and hooks only run from a plugin. So the
// sign-in page offers to install a small plugin holding just the hooks and
// `ml-recall`: no commands and no skill of its own, because the connector
// already installs the CLI, signs in, and ships the skills. The full plugin
// is not touched and keeps working as a product of its own.
//
//   node dev/build-auto-memory.mjs           # write the generated tree
//   node dev/build-auto-memory.mjs --check   # exit 1 if it is out of date
import { cpSync, existsSync, mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync, chmodSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const source = join(here, "../../workbuddy-plugin");
const target = join(here, "../memorylake-cli/skills/memorylake-cli/scripts/auto-memory");

export const MARKETPLACE = "memorylake-connector";
export const PLUGIN = "memorylake-auto";

// Sentences in the hooks that point at the full plugin's commands and skill,
// and what the connector says instead. Each must match exactly once, so a
// reworded source fails the build rather than shipping a stale pointer.
const RECONNECT = "reconnect the MemoryLake connector in WorkBuddy's connector list";
const REWORDED = [
  ["scripts/session-start.sh",
    "If the user asks about memory or MemoryLake, suggest running /memorylake:init.",
    `If the user asks about memory or MemoryLake, ask them to ${RECONNECT}.`],
  ["scripts/session-start.sh",
    "Suggest the user run /memorylake:init -- it installs the CLI and walks through login.",
    `Ask the user to ${RECONNECT} -- that installs the CLI and signs in.`],
  ["scripts/session-start.sh",
    "/memorylake:status can diagnose it.",
    `If it stays that way, ask the user to ${RECONNECT}.`],
  ["scripts/session-start.sh",
    "The memorylake skill covers query phrasing and reading results.",
    "The memorylake-cli-recall skill covers query phrasing and reading results."],
  ["bin/ml-recall",
    "run /memorylake:init to set it up",
    `ask the user to ${RECONNECT}`],
  ["bin/ml-recall",
    "run the setup (/memorylake:init in Claude Code, or ask Codex to set up memorylake)",
    `ask the user to ${RECONNECT} and turn on automatic memory`],
];

// Every hook goes through this. It is the connector's own, not the plugin's.
const RUN_SH = `#!/usr/bin/env bash
# Runs one hook of the MemoryLake connector's automatic memory.
# Generated by workbuddy-connector/dev/build-auto-memory.mjs; do not edit.
#
# The hooks themselves are copies of the MemoryLake plugin's. This wrapper
# adds the two things only the connector knows:
#   - the MemoryLake plugin does the same job, so when it is enabled these
#     hooks stand down; otherwise every turn would be reminded and synced twice;
#   - the connector keeps its CLI in WorkBuddy's own tools directory, which a
#     hook's PATH may not include; it goes first, so an older memorylake
#     elsewhere on the PATH is not the one that runs.
root=$(cd -- "$(dirname -- "\${BASH_SOURCE[0]}")" && pwd)
config="\${CODEBUDDY_CONFIG_DIR:-$HOME/.workbuddy}"
if grep -Eq '"memorylake@memorylake"[[:space:]]*:[[:space:]]*true' "$config/settings.json" 2>/dev/null; then
  exit 0
fi
PATH="$config/binaries/node/cli-connector-packages/bin:$PATH"
export PATH
exec "$root/$1"
`;

function build(out) {
  rmSync(out, { recursive: true, force: true });
  const plugin = join(out, PLUGIN);
  mkdirSync(join(out, ".workbuddy-plugin"), { recursive: true });
  mkdirSync(join(plugin, ".workbuddy-plugin"), { recursive: true });
  mkdirSync(join(plugin, "hooks"), { recursive: true });

  const manifest = JSON.parse(readFileSync(join(source, ".workbuddy-plugin/plugin.json"), "utf8"));
  const description = "Automatic memory for the MemoryLake connector: a search-first reminder every turn and per-turn conversation sync";
  writeFileSync(join(out, ".workbuddy-plugin/marketplace.json"), JSON.stringify({
    name: MARKETPLACE,
    description: "Installed by the MemoryLake connector's sign-in page",
    owner: { name: "MemoryLake" },
    plugins: [{ name: PLUGIN, source: `./${PLUGIN}`, description }],
  }, null, 2) + "\n");
  writeFileSync(join(plugin, ".workbuddy-plugin/plugin.json"), JSON.stringify({
    name: PLUGIN,
    displayName: "MemoryLake automatic memory",
    version: manifest.version,
    description,
    author: manifest.author,
    license: manifest.license,
  }, null, 2) + "\n");

  cpSync(join(source, "scripts"), join(plugin, "scripts"), { recursive: true });
  cpSync(join(source, "bin"), join(plugin, "bin"), { recursive: true });

  for (const [file, from, to] of REWORDED) {
    const path = join(plugin, file);
    const text = readFileSync(path, "utf8");
    if (text.split(from).length !== 2) throw new Error(`${file}: expected exactly one "${from}"`);
    writeFileSync(path, text.replace(from, to));
  }
  // Nothing a hook prints may still name a command the connector lacks.
  for (const file of walk(plugin)) {
    const stale = readFileSync(file, "utf8").split("\n").find((line) => !/^\s*#/.test(line) && line.includes("/memorylake:"));
    if (stale) throw new Error(`${relative(plugin, file)} still points at a plugin command: ${stale.trim()}`);
  }

  const hooks = JSON.parse(readFileSync(join(source, "hooks/hooks.json"), "utf8"));
  hooks.description = "MemoryLake automatic memory: standing instructions at session start, a search-first reminder and recall gate every turn, per-turn conversation sync.";
  const prefix = '"${CLAUDE_PLUGIN_ROOT}"/scripts/';
  for (const groups of Object.values(hooks.hooks)) {
    for (const hook of groups.flatMap((group) => group.hooks)) {
      if (!hook.command.startsWith(prefix)) throw new Error(`unexpected hook command: ${hook.command}`);
      hook.command = `${prefix}run.sh ${hook.command.slice(prefix.length)}`;
    }
  }
  writeFileSync(join(plugin, "hooks/hooks.json"), JSON.stringify(hooks, null, 2) + "\n");
  writeFileSync(join(plugin, "scripts/run.sh"), RUN_SH);
  chmodSync(join(plugin, "scripts/run.sh"), 0o755);
}

function walk(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) =>
    entry.isDirectory() ? walk(join(dir, entry.name)) : [join(dir, entry.name)]);
}

/** Relative path, mode and content of every file, for comparing two trees. */
function snapshot(dir) {
  if (!existsSync(dir)) return "";
  return walk(dir).sort().map((file) =>
    `${relative(dir, file)} ${(statSync(file).mode & 0o111) ? "x" : "-"}\n${readFileSync(file, "utf8")}`).join("\n\u0000");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  if (process.argv.includes("--check")) {
    const fresh = mkdtempSync(join(tmpdir(), "ml-auto-memory-"));
    try {
      build(fresh);
      if (snapshot(fresh) !== snapshot(target)) {
        console.error("auto-memory is out of date with workbuddy-plugin: run `node dev/build-auto-memory.mjs`");
        process.exit(1);
      }
      console.log("ok: auto-memory matches workbuddy-plugin");
    } finally {
      rmSync(fresh, { recursive: true, force: true });
    }
  } else {
    build(target);
    console.log(`wrote ${relative(process.cwd(), target)} (${walk(target).length} files)`);
  }
}
